#!/usr/bin/env python3
"""Build the Windows installer (Inno Setup) with the Q4 model and OCR bundled.

The installer is per-user (``%LOCALAPPDATA%\\Programs\\JianYin``), so it needs
no administrator rights. It installs the same files as the portable ZIP:
``JianYin.exe``, ``models/openai-privacy-filter-q4`` and the licence notices.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from release_common import MODEL_NOTICE, sha256  # noqa: E402

from jianyin_app.config import MODEL_DIR_NAME  # noqa: E402
from jianyin_app.model.download import validate_model_directory  # noqa: E402

APP_ID = "{{8F3C1D64-6A4B-4F0E-9C2D-7B5A1E8D3F21}"
ICON = ROOT / "jianyin_app" / "assets" / "jianyin.ico"


def find_iscc(explicit: str | None = None) -> Path:
    candidates: list[Path] = []
    if explicit:
        candidates.append(Path(explicit))
    configured = os.environ.get("ISCC_PATH")
    if configured:
        candidates.append(Path(configured))
    which = shutil.which("ISCC.exe") or shutil.which("iscc")
    if which:
        candidates.append(Path(which))
    for base in (
        r"C:\Program Files (x86)\Inno Setup 6",
        r"C:\Program Files\Inno Setup 6",
        r"C:\Program Files (x86)\Inno Setup 7",
        r"C:\Program Files\Inno Setup 7",
    ):
        candidates.append(Path(base) / "ISCC.exe")
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise SystemExit(
        "Inno Setup compiler (ISCC.exe) not found. Install Inno Setup 6 or set ISCC_PATH."
    )


def _quote(path: Path) -> str:
    return '"' + str(path).replace('"', '""') + '"'


def _quote_glob(path: Path, pattern: str) -> str:
    return '"' + str(path / pattern).replace('"', '""') + '"'


def write_script(
    *,
    script_path: Path,
    exe: Path,
    model_dir: Path,
    output: Path,
    version: str,
    iscc: Path,
) -> None:
    language_line = ""
    language_file = iscc.parent / "Languages" / "ChineseSimplified.isl"
    if language_file.is_file():
        language_line = (
            '[Languages]\n'
            'Name: "chinesesimplified"; MessagesFile: "compiler:Languages\\ChineseSimplified.isl"\n\n'
        )

    notices = []
    for name in ("LICENSE", "NOTICE", "THIRD_PARTY_NOTICES.md", "README.md"):
        source = ROOT / name
        if source.is_file():
            notices.append(f'Source: {_quote(source)}; DestDir: "{{app}}"; Flags: ignoreversion')
    licenses = ROOT / "third_party_licenses"
    if licenses.is_dir():
        notices.append(
            f"Source: {_quote_glob(licenses, '*')}; DestDir: \"{{app}}\\third_party_licenses\"; "
            "Flags: ignoreversion recursesubdirs createallsubdirs"
        )
    extra_dir = script_path.parent / "installer_extra"
    extra_dir.mkdir(parents=True, exist_ok=True)
    model_notice = extra_dir / "MODEL_NOTICE.txt"
    model_notice.write_text(MODEL_NOTICE, encoding="utf-8", newline="\n")
    notices.append(
        f'Source: {_quote(model_notice)}; DestDir: "{{app}}\\models\\{MODEL_DIR_NAME}"; '
        "Flags: ignoreversion"
    )

    script = f"""; Generated by scripts/package_windows_installer.py -- do not edit.
[Setup]
AppId={APP_ID}
AppName=笺隐 JianYin
AppVersion={version}
AppVerName=笺隐 JianYin {version}
AppPublisher=JianYin contributors
DefaultDirName={{localappdata}}\\Programs\\JianYin
DefaultGroupName=笺隐 JianYin
DisableProgramGroupPage=yes
PrivilegesRequired=lowest
ArchitecturesAllowed=x64
ArchitecturesInstallIn64BitMode=x64
OutputDir={_quote(output.parent)}
OutputBaseFilename={output.stem}
SetupIconFile={_quote(ICON)}
UninstallDisplayIcon={{app}}\\JianYin.exe
Compression=lzma2/max
SolidCompression=yes
WizardStyle=modern
CloseApplications=yes
RestartApplications=no
SetupLogging=yes

{language_line}[Tasks]
Name: "desktopicon"; Description: "创建桌面快捷方式"; GroupDescription: "附加任务："; Flags: unchecked

[Files]
Source: {_quote(exe)}; DestDir: "{{app}}"; Flags: ignoreversion
Source: {_quote_glob(model_dir, '*')}; DestDir: "{{app}}\\models\\{MODEL_DIR_NAME}"; Excludes: ".cache\\*,.DS_Store"; Flags: ignoreversion recursesubdirs createallsubdirs
{chr(10).join(notices)}

[Icons]
Name: "{{group}}\\笺隐 JianYin"; Filename: "{{app}}\\JianYin.exe"
Name: "{{autodesktop}}\\笺隐 JianYin"; Filename: "{{app}}\\JianYin.exe"; Tasks: desktopicon

[Run]
Filename: "{{app}}\\JianYin.exe"; Description: "启动笺隐"; Flags: nowait postinstall skipifsilent

[UninstallDelete]
Type: filesandordirs; Name: "{{app}}\\models"
"""
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text(script, encoding="utf-8-sig", newline="\r\n")


def build_installer(
    *,
    exe: Path,
    model_dir: Path,
    output: Path,
    version: str,
    iscc_path: str | None = None,
) -> dict[str, object]:
    if not exe.is_file():
        raise SystemExit(f"executable not found: {exe}")
    exe = exe.resolve()
    model_root = validate_model_directory(model_dir)
    iscc = find_iscc(iscc_path)
    output = output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists():
        output.unlink()

    script_path = ROOT / "build" / "installer.iss"
    write_script(
        script_path=script_path,
        exe=exe,
        model_dir=model_root,
        output=output,
        version=version,
        iscc=iscc,
    )
    command = [str(iscc), str(script_path)]
    print("$ " + " ".join(command), flush=True)
    subprocess.run(command, check=True, cwd=ROOT)
    if not output.is_file():
        raise SystemExit(f"installer was not created: {output}")
    return {
        "status": "ok",
        "output": str(output),
        "size": output.stat().st_size,
        "sha256": sha256(output),
        "version": version,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a Windows JianYin installer with Q4 model")
    parser.add_argument("--exe", required=True, type=Path)
    parser.add_argument("--model-dir", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--version", default="0.2.0")
    parser.add_argument("--iscc", default=None)
    args = parser.parse_args(argv)
    result = build_installer(
        exe=args.exe,
        model_dir=args.model_dir,
        output=args.output,
        version=args.version,
        iscc_path=args.iscc,
    )
    print(json.dumps(result, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
